-- RAMS feature (Risk Assessment & Method Statement) — schema
-- Run on SANDBOX first (erbrflbialsyxbjawopy); LIVE only at cutover.
-- Patterns follow contract-signing.sql:
--   * NO foreign key to quotes — a signed RAMS is a legal record and must
--     survive quote deletion.
--   * expired is DERIVED from expires_at, never stored.
--   * per-SIGNER tokens live inside the signers jsonb array; the edge function
--     looks rows up by token containment, hence the GIN jsonb_path_ops index.
-- After running: NOTIFY pgrst, 'reload schema';  (PostgREST schema-cache gotcha)
